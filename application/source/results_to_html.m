function txt = results_to_html(result, img_b64)
%RESULTS_TO_HTML  Build a self-contained HTML results report (as text).
%   txt = RESULTS_TO_HTML(result, img_b64) returns a single HTML document with
%   the plain-language elaboration, the headline numbers, and the fitted-curve
%   chart embedded inline as a base64 PNG (img_b64, '' for none). Opens in any
%   browser; nothing external to load. Pure (no file IO). [compiled-app]
    if nargin < 2 || isempty(img_b64), img_b64 = ''; end
    u = 'mm';
    if isfield(result, 'unit') && ~isempty(result.unit), u = result.unit; end
    mu  = html_field(result,'mu',NaN);   sg = html_field(result,'sigma',NaN);
    lo  = html_field(result,'mu_lo',NaN); hi = html_field(result,'mu_hi',NaN);
    n   = numel(result.levels);
    confidence = 100 * html_field(result, 'confidence_level', 0.95);
    decision = result_decision_summary(result);

    if decision.supported
        decisionClass = 'supported';
        decisionTitle = 'Supported operating instruction';
        decisionText = html_escape(decision.operating_instruction);
        buildText = sprintf('<p><strong>Physical build:</strong> %s</p>', ...
            html_escape(char(decision.physical_build_instruction)));
    else
        decisionClass = 'not-supported';
        decisionTitle = 'Operating instruction not established';
        decisionText = html_escape(decision.explanation);
        buildText = '';
    end

    if isempty(img_b64)
        imgTag = '<p><em>(chart not available)</em></p>';
    else
        imgTag = sprintf('<img alt="fitted interaction curve" style="max-width:100%%" src="data:image/png;base64,%s">', img_b64);
    end

    txt = strjoin({ ...
      '<!doctype html><html><head><meta charset="utf-8">', ...
      '<title>Neyer gap-study results</title>', ...
      '<style>body{font-family:system-ui,Arial,sans-serif;max-width:900px;margin:2rem auto;padding:0 1rem;color:#243039}h1{font-size:1.65rem}.decision{border-radius:10px;padding:1rem 1.2rem;margin:1rem 0}.supported{background:#eaf5ee;border:2px solid #2a7040}.not-supported{background:#fff4df;border:2px solid #a56c16}.big{font-size:1.3rem;font-weight:bold}.fact{background:#f3f6f7;border-left:5px solid #54717d;padding:.75rem 1rem}img{border:1px solid #ccd5d8;border-radius:8px}</style>', ...
      '</head><body>', ...
      '<h1>Neyer gap-study results</h1>', ...
      sprintf('<section class="decision %s"><h2>%s</h2><p>%s</p>%s</section>', ...
        decisionClass, decisionTitle, decisionText, buildText), ...
      sprintf('<p class="big">Middle gap (about 50%% interaction): %.2f %s</p>', mu, u), ...
      sprintf('<p>At this gap, interaction is estimated to occur in about half of similar articles. It is not the reliable operating gap.</p>'), ...
      sprintf('<p>We are %.4g%% confident the true middle gap is between %.2f and %.2f %s. Based on %d tests.</p>', confidence, lo, hi, u, n), ...
      sprintf('<div class="fact"><strong>Overall variation: %.2f %s.</strong> This describes how much the entire tested process varies from article to article around the middle gap.</div>', sg, u), ...
      '<p>Smaller gaps make interaction more likely. Larger gaps make interaction less likely. The edge-gap estimates are less certain than the middle gap.</p>', ...
      '<h2>Fitted curve</h2>', imgTag, ...
      '<hr><p style="color:#777;font-size:.85rem">Generated by the D-Optimal Sensitivity Tool. Neyer (1994) D-optimal sensitivity method.</p>', ...
      '</body></html>' }, sprintf('\n'));
end

function text = html_escape(text)
    text = strrep(char(string(text)), '&', '&amp;');
    text = strrep(text, '<', '&lt;');
    text = strrep(text, '>', '&gt;');
    text = strrep(text, '"', '&quot;');
end

function v = html_field(s, name, dflt)
    if isfield(s, name) && ~isempty(s.(name)) && ~isnan(s.(name)), v = s.(name);
    else, v = dflt; end
end
